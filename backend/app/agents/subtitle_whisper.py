import logging
import math
from pathlib import Path
import time
from typing import Any, Dict, List, Optional
from faster_whisper import WhisperModel

from app.agents.base import BaseAgent
from app.core.config import settings

logger = logging.getLogger(__name__)

# Global Singleton WhisperModel instance
_GLOBAL_WHISPER_MODEL: Optional[WhisperModel] = None


def get_whisper_singleton() -> WhisperModel:
    """Returns or initializes the global WhisperModel singleton once per worker process."""
    global _GLOBAL_WHISPER_MODEL
    if _GLOBAL_WHISPER_MODEL is None:
        logger.info("Initializing Singleton WhisperModel('base', device='cpu', compute_type='int8', cpu_threads=4)...")
        _GLOBAL_WHISPER_MODEL = WhisperModel(
            "base",
            device="cpu",
            compute_type="int8",
            cpu_threads=4,
        )
    return _GLOBAL_WHISPER_MODEL


class SubtitleWhisperAgent(BaseAgent):
    """Transcribes audio using faster-whisper with word-level timestamps and
    generates highly engaging SubStation Alpha (.ass) subtitles with viral
    short-form highlighting (yellow active word, 2-3 word grouping).
    Uses a singleton WhisperModel instance across the worker process.
    """

    def __init__(self) -> None:
        super().__init__(name="subtitle_whisper")

    @property
    def model(self) -> WhisperModel:
        return get_whisper_singleton()

    @staticmethod
    def format_ass_time(seconds: float) -> str:
        """Format seconds to ASS timestamp format: H:MM:SS.cc"""
        if seconds < 0:
            seconds = 0.0
        hours = int(seconds // 3600)
        minutes = int((seconds % 3600) // 60)
        secs = int(seconds % 60)
        centisecs = int(round((seconds - math.floor(seconds)) * 100))
        if centisecs >= 100:
            centisecs = 99
        return f"{hours}:{minutes:02d}:{secs:02d}.{centisecs:02d}"

    def build_ass_content(self, words: List[Dict[str, Any]]) -> str:
        """Construct SubStation Alpha formatted script with dynamic active-word styling."""
        header = """[Script Info]
; Script generated by DASMO Office AI Factory
Title: DASMO Shorts Subtitles
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
PlayResX: 1080
PlayResY: 1920

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: ViralShorts,Montserrat,82,&H00FFFFFF,&H000000FF,&H00000000,&H90000000,-1,0,0,0,100,100,2,0,1,6,4,2,80,80,520,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
        lines = [header]
        chunk_size = 3
        pop_active_tag = "{\\fscx120\\fscy120\\t(0,100,\\fscx100\\fscy100)\\c&H0000FFFF&}"
        reset_tag = "{\\fscx100\\fscy100\\c&H00FFFFFF&}"

        for i in range(0, len(words), chunk_size):
            chunk = words[i : i + chunk_size]
            for current_idx, active_word in enumerate(chunk):
                start_str = self.format_ass_time(active_word["start"])
                end_str = self.format_ass_time(active_word["end"])

                styled_tokens = []
                for idx, w in enumerate(chunk):
                    text = w["word"].strip().upper()
                    if idx == current_idx:
                        styled_tokens.append(f"{pop_active_tag}{text}{reset_tag}")
                    else:
                        styled_tokens.append(text)

                line_text = " ".join(styled_tokens)
                dialogue = f"Dialogue: 0,{start_str},{end_str},ViralShorts,,0,0,0,,{line_text}\n"
                lines.append(dialogue)

        return "".join(lines)

    async def run(self, input_data: Dict[str, Any]) -> Dict[str, Any]:
        """Transcribe audio with word-level timestamps and write .ass subtitles."""
        t0 = time.perf_counter()
        short_id = input_data.get("short_id")
        audio_path_str = input_data.get("audio_path")

        if not short_id:
            raise ValueError("SubtitleWhisperAgent requires a valid 'short_id'")
        if not audio_path_str:
            raise ValueError("SubtitleWhisperAgent requires a valid 'audio_path'")

        audio_file = Path(audio_path_str)
        if not audio_file.exists():
            raise FileNotFoundError(f"Audio file '{audio_file}' does not exist.")

        subtitles_dir = Path(settings.MEDIA_DIR) / "subtitles" / str(short_id)
        subtitles_dir.mkdir(parents=True, exist_ok=True)
        ass_file = subtitles_dir / "subtitles.ass"

        self.logger.info("Transcribing master audio with faster-whisper for Short #%s...", short_id)

        segments, info = self.model.transcribe(
            str(audio_file),
            beam_size=1,
            word_timestamps=True,
            language="es",
            vad_filter=True,
        )

        words: List[Dict[str, Any]] = []
        for segment in segments:
            if segment.words:
                for w in segment.words:
                    words.append({
                        "word": w.word,
                        "start": w.start,
                        "end": w.end,
                        "probability": w.probability,
                    })

        self.logger.info("Extracted %d words from transcription.", len(words))

        # Fallback if no words detected
        if not words:
            self.logger.warning("No words extracted; writing minimal placeholder subtitle.")
            words = [{"word": "DASMO", "start": 0.0, "end": 2.0, "probability": 1.0}]

        ass_content = self.build_ass_content(words)
        with open(ass_file, "w", encoding="utf-8") as f:
            f.write(ass_content)

        elapsed = time.perf_counter() - t0
        self.logger.info("SubtitleWhisperAgent completed in %.2f seconds at '%s'", elapsed, ass_file)

        return {
            "status": "success",
            "agent": self.name,
            "short_id": short_id,
            "subtitles_path": str(ass_file),
            "words_count": len(words),
            "elapsed_seconds": elapsed,
        }
